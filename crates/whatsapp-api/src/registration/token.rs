//! Registration-token derivation observed in the signed comparison APK.
//!
//! This is deliberately version scoped. It reproduces the local token helper
//! in WhatsApp 2.26.37.70; it does not assert that another build uses the same
//! salt, resources, certificate, or digest inputs.

use hmac::{Hmac, Mac};
use md5::{Digest as _, Md5};
use pbkdf2::pbkdf2_hmac;
use sha1::Sha1;
use zeroize::{Zeroize, Zeroizing};

use crate::model::phone::PhoneNumber;
use crate::{Error, Result};

/// Maximum accepted bytes for the APK logo resource used as PBKDF2 password
/// material. The observed hdpi resource is much smaller than this bound.
pub const MAX_TOKEN_LOGO_BYTES: usize = 2 << 20;
/// Maximum accepted signing-certificate DER length.
pub const MAX_TOKEN_CERTIFICATE_BYTES: usize = 256 << 10;
/// Maximum accepted primary DEX length.
pub const MAX_TOKEN_DEX_BYTES: usize = 256 << 20;

const COMPARISON_PBKDF2_ITERATIONS: u32 = 128;
const COMPARISON_PBKDF2_KEY_BYTES: usize = 64;
const COMPARISON_TOKEN_SALT: &[u8] = &[
    0x3e, 0x44, 0xf0, 0x29, 0x26, 0x6a, 0x51, 0xf0, 0x14, 0xc9, 0x1d, 0x2b, 0x3d, 0x0f, 0x21, 0x60,
    0x9d, 0x30, 0x36, 0xc4, 0x10, 0xdd, 0xd5, 0xb5, 0xfb, 0x74, 0x82, 0x9f, 0x24, 0xd7, 0x21, 0xf1,
    0x00, 0xc7, 0x14, 0xbb, 0xe4, 0x5c, 0x24, 0x0d, 0xfe, 0x3b, 0xc0, 0xdb, 0xff, 0x73, 0xca, 0x4f,
    0xde, 0x9d, 0x06, 0x5c, 0xa4, 0x7a, 0x38, 0xe4, 0x26, 0x87, 0x21, 0x11, 0xc3, 0x1e, 0xf8, 0x7f,
    0x0d, 0x51, 0x61, 0x25, 0x35, 0xd0, 0x8e, 0x2b, 0xd6, 0x0c, 0x81, 0x54, 0x36, 0xd1, 0x27, 0x8d,
    0x29, 0x89, 0xd8, 0xcc, 0xe3, 0x51, 0xb5, 0x23, 0x5a, 0x0d,
];

/// APK-owned inputs consumed by the comparison build's token helper.
///
/// The logo must be `res/drawable-hdpi-v4/about_logo.png` when the APK does
/// not contain the non-`-v4` hdpi path. The certificate is the first signing
/// certificate's DER encoding, equivalent to Android `Signature.toByteArray`.
#[derive(Debug, Clone, Copy)]
pub struct ComparisonTokenMaterial<'a> {
    /// Android application package name.
    pub package_name: &'a str,
    /// Exact bytes of the APK's selected hdpi `about_logo.png` resource.
    pub about_logo: &'a [u8],
    /// First Android signing certificate in DER form.
    pub signing_certificate_der: &'a [u8],
    /// Exact uncompressed bytes of the APK's primary `classes.dex` entry.
    pub classes_dex: &'a [u8],
}

/// Reproduce the `/v2/code` `token` value generated by WhatsApp 2.26.37.70.
///
/// The phone contribution is the national number only (`in`), not the country
/// code (`cc`) and not a leading `+`. The returned value zeroizes on drop.
pub fn derive_comparison_registration_token(
    phone: &PhoneNumber,
    material: ComparisonTokenMaterial<'_>,
) -> Result<Zeroizing<String>> {
    validate_material(material)?;

    let mut password = Zeroizing::new(Vec::with_capacity(
        material.package_name.len() + material.about_logo.len(),
    ));
    password.extend_from_slice(material.package_name.as_bytes());
    password.extend_from_slice(material.about_logo);

    let mut key = Zeroizing::new([0u8; COMPARISON_PBKDF2_KEY_BYTES]);
    pbkdf2_hmac::<Sha1>(
        password.as_slice(),
        COMPARISON_TOKEN_SALT,
        COMPARISON_PBKDF2_ITERATIONS,
        key.as_mut_slice(),
    );

    let mut mac = Hmac::<Sha1>::new_from_slice(key.as_slice())
        .map_err(|_| Error::invalid("registration_token_key", "invalid HMAC key"))?;
    mac.update(material.signing_certificate_der);
    mac.update(&Md5::digest(material.classes_dex));
    mac.update(phone.national_number().as_bytes());
    let mut digest = mac.finalize().into_bytes();
    let token = standard_base64_padded(&digest);
    digest.as_mut_slice().zeroize();
    Ok(Zeroizing::new(token))
}

fn validate_material(material: ComparisonTokenMaterial<'_>) -> Result<()> {
    if material.package_name.is_empty()
        || material.package_name.len() > 255
        || !material
            .package_name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_'))
    {
        return Err(Error::invalid(
            "package_name",
            "must contain 1..=255 ASCII package-name bytes",
        ));
    }
    for (field, value, limit) in [
        ("about_logo", material.about_logo, MAX_TOKEN_LOGO_BYTES),
        (
            "signing_certificate_der",
            material.signing_certificate_der,
            MAX_TOKEN_CERTIFICATE_BYTES,
        ),
        ("classes_dex", material.classes_dex, MAX_TOKEN_DEX_BYTES),
    ] {
        if value.is_empty() || value.len() > limit {
            return Err(Error::invalid(
                field,
                format!("must contain 1..={limit} bytes"),
            ));
        }
    }
    Ok(())
}

fn standard_base64_padded(input: &[u8]) -> String {
    const TABLE: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut output = String::with_capacity(input.len().div_ceil(3) * 4);
    for chunk in input.chunks(3) {
        let first = chunk[0];
        output.push(char::from(TABLE[usize::from(first >> 2)]));
        if let Some(&second) = chunk.get(1) {
            output.push(char::from(
                TABLE[usize::from(((first & 0x03) << 4) | (second >> 4))],
            ));
            if let Some(&third) = chunk.get(2) {
                output.push(char::from(
                    TABLE[usize::from(((second & 0x0f) << 2) | (third >> 6))],
                ));
                output.push(char::from(TABLE[usize::from(third & 0x3f)]));
            } else {
                output.push(char::from(TABLE[usize::from((second & 0x0f) << 2)]));
                output.push('=');
            }
        } else {
            output.push(char::from(TABLE[usize::from((first & 0x03) << 4)]));
            output.push_str("==");
        }
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn salt_matches_committed_apk_bytecode() {
        // HQP.<clinit>, const-string at 0x0000; independently copied as Base64
        // from docs/protocol/apk/2.26.37.70/registration-token-salt.txt.
        let evidence = "PkTwKSZqUfAUyR0rPQ8hYJ0wNsQQ3dW1+3SCnyTXIfEAxxS75FwkDf47wNv/c8pP3p0GXKR6OOQmhyERwx74fw1RYSU10I4r1gyBVDbRJ40pidjM41G1I1oN";
        let encoded = standard_base64_padded(COMPARISON_TOKEN_SALT);
        assert_eq!(encoded, evidence);
    }

    #[test]
    fn standard_base64_keeps_android_no_wrap_padding() {
        assert_eq!(standard_base64_padded(b""), "");
        assert_eq!(standard_base64_padded(b"f"), "Zg==");
        assert_eq!(standard_base64_padded(b"fo"), "Zm8=");
        assert_eq!(standard_base64_padded(b"foo"), "Zm9v");
        assert_eq!(standard_base64_padded(&[0xfb, 0xff, 0xef]), "+//v");
    }

    #[test]
    fn derivation_is_stable_and_phone_uses_national_number() {
        let phone = PhoneNumber::new(44, "7700900123").unwrap();
        let token = derive_comparison_registration_token(
            &phone,
            ComparisonTokenMaterial {
                package_name: "com.whatsapp",
                about_logo: b"logo fixture",
                signing_certificate_der: b"certificate fixture",
                classes_dex: b"dex fixture",
            },
        )
        .unwrap();
        // Independently calculated with Python hashlib.pbkdf2_hmac + hmac,
        // using the Base64 salt decoded directly from the APK evidence.
        assert_eq!(token.as_str(), "qVj97PKhWFvdbTpFsH7gSeiqQTk=");
    }

    #[test]
    fn rejects_empty_or_unbounded_material() {
        let phone = PhoneNumber::new(1, "5551234567").unwrap();
        let valid = ComparisonTokenMaterial {
            package_name: "com.whatsapp",
            about_logo: b"logo",
            signing_certificate_der: b"cert",
            classes_dex: b"dex",
        };
        assert!(derive_comparison_registration_token(&phone, valid).is_ok());
        assert!(
            derive_comparison_registration_token(
                &phone,
                ComparisonTokenMaterial {
                    about_logo: b"",
                    ..valid
                }
            )
            .is_err()
        );
    }
}
