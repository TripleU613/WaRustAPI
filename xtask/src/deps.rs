//! Dependency graph audit (README section 2.4).
//!
//! Walks the *normal* dependency edges of the release crates for the Linux
//! x86_64 target (approximated from `cfg` strings) and reports packages with
//! build scripts, `links` keys, `-sys` names and known native crypto/storage
//! implementations. The report is written to
//! `docs/protocol/dependency-report.md`.

use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::fs;
use std::path::Path;

use cargo_metadata::{CargoOpt, DependencyKind, MetadataCommand, PackageId};

/// Crates that are never acceptable in the release graph under the strict
/// pure-Rust contract.
const DENIED: &[&str] = &[
    "ring",
    "aws-lc-sys",
    "aws-lc-rs",
    "openssl-sys",
    "openssl",
    "native-tls",
    "libsqlite3-sys",
    "rusqlite",
    "zstd-sys",
    "bzip2-sys",
    "libz-sys",
    "libz-ng-sys",
    "boring-sys",
];

/// Crates with build scripts that are known to be pure Rust (the build script
/// only probes the compiler or emits cfgs). Listed so the report can mark them
/// reviewed; anything else with a build script is flagged for review.
const REVIEWED_BUILD_SCRIPTS: &[&str] = &[
    // Reviewed 2026-09-17: cfg probes only, no compilation or downloads.
    "redb",
    "snow",
    "zmij",
    "quote",
    "rustc_version",
    "libc",
    "proc-macro2",
    "serde",
    "serde_core",
    "serde_json",
    "getrandom",
    "typenum",
    "generic-array",
    "lock_api",
    "parking_lot_core",
    "slab",
    "thiserror",
    "anyhow",
    "num-traits",
    "crossbeam-utils",
    "rustix",
    "curve25519-dalek",
    "zerocopy",
    "syn",
    "portable-atomic",
    "httparse",
    "windows_x86_64_gnu",
    "cpufeatures",
    "semver",
    "camino",
    "rustversion",
    "autocfg",
    "version_check",
    "indexmap",
    "hashbrown",
    "ahash",
    "memchr",
    "bitflags",
];

struct Target {
    package: &'static str,
    features: Vec<&'static str>,
    no_default: bool,
}

fn linux_x86_64(cfg: Option<&str>) -> bool {
    let Some(cfg) = cfg else { return true };
    let c = cfg.to_ascii_lowercase();
    let negative = [
        "windows",
        "wasm",
        "wasi",
        "apple",
        "macos",
        "ios",
        "android",
        "hermit",
        "redox",
        "solaris",
        "fuchsia",
        "emscripten",
        "target_env = \"sgx\"",
        "aarch64",
        "arm",
        "riscv",
        "powerpc",
        "mips",
        "loongarch",
        "s390x",
        "sparc",
    ];
    if c.starts_with("cfg(not(") {
        return true;
    }
    !negative.iter().any(|n| c.contains(n))
}

pub fn audit(root: &Path, strict: bool) -> Result<(), String> {
    let targets = [
        Target {
            package: "whatsapp-api",
            features: vec![],
            no_default: false,
        },
        Target {
            package: "whatsapp-api",
            features: vec!["experimental-noise"],
            no_default: false,
        },
        Target {
            package: "whatsapp-cli",
            features: vec![],
            no_default: false,
        },
    ];
    let mut report = String::new();
    report.push_str("# Dependency audit report\n\n");
    report.push_str(
        "Generated by `cargo run -p xtask -- dependency-audit`. Do not edit by hand.\n\n",
    );
    report.push_str("Scope: normal dependency edges only (no dev/build dependencies), Linux x86_64 approximated from `cfg` strings. Build dependencies of each listed crate are reviewed separately through the *build script* column.\n\n");
    let mut violations = Vec::new();
    for t in &targets {
        let mut cmd = MetadataCommand::new();
        cmd.manifest_path(root.join("Cargo.toml"));
        if t.no_default {
            cmd.features(CargoOpt::NoDefaultFeatures);
        }
        if !t.features.is_empty() {
            cmd.features(CargoOpt::SomeFeatures(
                t.features
                    .iter()
                    .map(|s| format!("{}/{}", t.package, s))
                    .collect(),
            ));
        }
        let meta = cmd.exec().map_err(|e| format!("cargo metadata: {e}"))?;
        let resolve = meta.resolve.as_ref().ok_or("no resolve graph")?;
        let by_id: BTreeMap<&PackageId, &cargo_metadata::Package> =
            meta.packages.iter().map(|p| (&p.id, p)).collect();
        let nodes: BTreeMap<&PackageId, &cargo_metadata::Node> =
            resolve.nodes.iter().map(|n| (&n.id, n)).collect();
        let start = meta
            .packages
            .iter()
            .find(|p| p.name.as_str() == t.package)
            .ok_or_else(|| format!("package {} not found", t.package))?;
        let mut seen: BTreeSet<&PackageId> = BTreeSet::new();
        let mut queue = VecDeque::new();
        queue.push_back(&start.id);
        seen.insert(&start.id);
        while let Some(id) = queue.pop_front() {
            let Some(node) = nodes.get(id) else { continue };
            for dep in &node.deps {
                let normal = dep.dep_kinds.iter().any(|k| {
                    k.kind == DependencyKind::Normal
                        && linux_x86_64(k.target.as_ref().map(|p| p.to_string()).as_deref())
                });
                if normal && seen.insert(&dep.pkg) {
                    queue.push_back(&dep.pkg);
                }
            }
        }
        let label = format!(
            "{}{}",
            t.package,
            if t.features.is_empty() {
                String::new()
            } else {
                format!(" +{}", t.features.join(","))
            }
        );
        report.push_str(&format!("## `{label}`\n\n"));
        report.push_str(&format!(
            "Resolved normal-edge packages: {}\n\n",
            seen.len()
        ));
        report.push_str("| Crate | Version | Enabled features | Build script | `links` | Flags |\n|---|---|---|---|---|---|\n");
        let mut rows: Vec<_> = seen
            .iter()
            .filter_map(|id| by_id.get(id).map(|p| (p, nodes.get(id))))
            .collect();
        rows.sort_by(|a, b| a.0.name.cmp(&b.0.name).then(a.0.version.cmp(&b.0.version)));
        for (p, node) in rows {
            let has_build = p
                .targets
                .iter()
                .any(|t| t.kind.iter().any(|k| k.to_string() == "custom-build"));
            let name = p.name.as_str();
            let mut flags = Vec::new();
            if DENIED.contains(&name) {
                flags.push("**DENIED**");
                violations.push(format!("{label}: {name} {}", p.version));
            }
            if name.ends_with("-sys") {
                flags.push("`-sys` name (review)");
            }
            if has_build && !REVIEWED_BUILD_SCRIPTS.contains(&name) && !DENIED.contains(&name) {
                flags.push("build script needs review");
            }
            if p.links.is_some() {
                flags.push("native link");
            }
            let features = node
                .map(|n| {
                    n.features
                        .iter()
                        .map(|f| f.as_str())
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .unwrap_or_default();
            report.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} |\n",
                name,
                p.version,
                if features.is_empty() {
                    "-".to_string()
                } else {
                    format!("`{features}`")
                },
                if has_build { "yes" } else { "no" },
                p.links.as_deref().unwrap_or("-"),
                if flags.is_empty() {
                    "-".to_string()
                } else {
                    flags.join("; ")
                },
            ));
        }
        report.push('\n');
    }
    report.push_str("## Denied crate list\n\n");
    for d in DENIED {
        report.push_str(&format!("- `{d}`\n"));
    }
    report.push_str("\n## Result\n\n");
    if violations.is_empty() {
        report.push_str("No denied crates in any audited graph.\n");
    } else {
        report.push_str("Violations:\n\n");
        for v in &violations {
            report.push_str(&format!("- {v}\n"));
        }
    }
    let out = root.join("docs/protocol/dependency-report.md");
    fs::create_dir_all(out.parent().unwrap()).map_err(|e| e.to_string())?;
    fs::write(&out, report).map_err(|e| e.to_string())?;
    eprintln!("wrote {}", out.display());
    if strict && !violations.is_empty() {
        return Err(format!("denied crates present: {}", violations.join(", ")));
    }
    Ok(())
}
